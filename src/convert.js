/**
 * Converting a DSH bundle into a pi package.
 *
 * The runtime path registers a DSH bundle's tools into the current session, which
 * is invisible to pi's own plugin list and cannot be switched off per plugin. What
 * a user actually wants from "a DSH plugin in pi" is the thing pi shows in its
 * settings: an entry with a toggle. So this writes a real pi package - manifest,
 * generated extension, bundled copy of the DSH code - and hands it to `pi install`.
 *
 * The generated extension is thin on purpose. It does not re-implement the
 * bridging; it asks the installed bridge to load the bundled copy once at startup
 * and replay it into pi, which is the same code path the runtime bridge already
 * uses. That keeps one implementation of "what a DSH capability means in pi", and
 * means a fix to the bridge fixes every package it ever generated.
 *
 * @module src/convert.js
 */
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'
import os from 'node:os'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const BRIDGE_ROOT = path.resolve(HERE, '..')

/** Where generated packages live: beside pi's own state, not inside the bridge. */
export function convertedRoot (env = process.env, home = env.USERPROFILE || env.HOME || os.homedir()) {
  return path.join(home, '.pi', 'agent', 'dsh-converted')
}

/** A filesystem-safe directory name for a package. */
export function slugOf (name) {
  return String(name || 'dsh-plugin')
    .replace(/^@/, '')
    .replace(/[^a-zA-Z0-9._-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'dsh-plugin'
}

/**
 * The manifest of a converted package. Pure, so its shape can be asserted.
 *
 * `keywords: ["pi-package"]` is what makes pi treat it as one, and `pi.extensions`
 * is what makes the panel list it with a toggle rather than as an opaque folder.
 */
export function manifestFor (info, slug) {
  return {
    name: 'dsh-' + slug,
    version: String(info.version || '0.0.0'),
    type: 'module',
    description: 'Converted from the DSH bundle ' + (info.name || slug) + ' by dsh-pi-bridge.',
    keywords: ['pi-package', 'dsh-plugin'],
    pi: { extensions: ['./extensions'] },
  }
}

/**
 * The generated extension.
 *
 * It forwards, it does not transliterate. A DSH plugin is only itself when its
 * `ctx.llm`, session and skill registry are the real host's, so the generated
 * package asks the bridge for a DSH host and registers one forwarding tool per
 * capability - the same path the runtime bridge uses, which is why a fix there
 * fixes every package this ever generated.
 *
 * Three things are load-bearing: the bridge is imported by absolute file URL,
 * because a generated package has no dependency edge that would let it resolve
 * `dsh-pi-bridge` itself; the bundle spec is baked in, so loading needs no
 * network beyond the bundle's own first install; and a host that cannot start is
 * reported through `pi.ui` rather than thrown, because an extension that throws
 * during load takes the whole session's tools with it.
 *
 * @param {{bundleName:string, prefix:string, bridgeRoot:string, source:string}} o
 * @returns {string} module text
 */
export function extensionSource (o) {
  const url = (p) => pathToFileURL(path.join(o.bridgeRoot || BRIDGE_ROOT, 'src', p)).href
  return `/**
 * Generated by dsh-pi-bridge from ${o.source}
 * Do not edit: re-run the conversion instead, so the change survives.
 */
const SPEC = ${JSON.stringify(o.source)}
const PREFIX = ${JSON.stringify(o.prefix || '')}

export default async function dshConverted (pi) {
  const { ensureDshHost } = await import(${JSON.stringify(url('dsh-supervisor.js'))})
  const { dshHostLoad, dshHostCall, dshParamsToSchema } = await import(${JSON.stringify(url('dsh-host-client.js'))})
  const notify = (m, k) => { if (pi.ui && typeof pi.ui.notify === 'function') pi.ui.notify(m, k) }
  // One line on stdout, because "the plugin is installed but nothing happened" is
  // indistinguishable from "the adapter never loaded" without it.
  console.log('[dsh-converted] ' + ${JSON.stringify(o.bundleName)} + ': loading')

  let host
  try {
    host = await ensureDshHost({ log: () => {} })
  } catch (e) {
    notify(${JSON.stringify(o.bundleName)} + ': no DSH host available - ' + String((e && e.message) || e), 'error')
    return
  }
  const loaded = await dshHostLoad(SPEC, {})
  if (!loaded || !loaded.ok) {
    notify(${JSON.stringify(o.bundleName)} + ': DSH refused to load it - ' + ((loaded && loaded.error) || 'no reply'), 'error')
    return
  }

  for (const t of loaded.tools || []) {
    const name = PREFIX ? PREFIX + '_' + t.name : t.name
    pi.registerTool({
      name,
      label: t.name,
      description: (t.description || '(no description)') + ' [runs natively inside DSH]',
      parameters: dshParamsToSchema(t.parameters),
      async execute (_id, params) {
        const res = await dshHostCall(t.name, params || {})
        if (!res || !res.ok) {
          return { content: [{ type: 'text', text: t.name + ' failed: ' + ((res && res.error) || 'no result') }], details: { error: true, viaDsh: true } }
        }
        const payload = res.result && typeof res.result === 'object' && res.result.result !== undefined ? res.result : { result: res.result }
        const text = typeof payload.result === 'string' ? payload.result : JSON.stringify(payload.result === undefined ? payload : payload.result)
        return { content: [{ type: 'text', text: (payload.ok === false ? 'error: ' : '') + text }], details: { viaDsh: true, tool: t.name } }
      },
    })
  }
  for (const c of loaded.commands || []) {
    pi.registerCommand(c.name, {
      description: (c.description || '') + ' [runs natively inside DSH]',
      handler: async () => notify('DSH command ' + c.name + ' has no pi equivalent to run it from here', 'warn'),
    })
  }
  if (!(loaded.tools || []).length) notify(${JSON.stringify(o.bundleName)} + ': loaded in DSH but exposes no tools', 'warn')
}
`
}

/** Run pi's own installer, so the package is registered where pi reads packages. */
function piInstall (dir) {
  const res = spawnSync('pi', ['install', dir], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
    timeout: 120000,
    windowsHide: true,
  })
  const out = String((res && (res.stdout || res.stderr)) || '').trim()
  return { ok: res && res.status === 0, out: out.split('\n').slice(-3).join(' ').slice(0, 300) }
}

/**
 * Convert a DSH bundle into an installed pi package.
 *
 * @param {string} spec npm:, git:, or a path
 * @param {{log?:function, prefix?:string, env?:object, bridgeRoot?:string, install?:boolean}} [options]
 * @returns {Promise<{dir:string, name:string, tools:string[], commands:string[], installed:boolean, note:string}>}
 */
export async function convertToPiPackage (spec, options = {}) {
  const log = options.log || (() => {})
  const env = options.env || process.env
  const { loadForeign } = await import('./load.js')

  log('reading ' + spec)
  const captured = await loadForeign(spec, { host: 'dsh' })
  const info = captured.info || {}
  const slug = slugOf(info.name || spec)
  const dir = path.join(convertedRoot(env), slug)
  const mirror = captured.mirror
  if (!mirror || !existsSync(mirror)) throw new Error('the bundle could not be staged on disk: ' + spec)

  await rm(dir, { recursive: true, force: true })
  await mkdir(path.join(dir, 'extensions'), { recursive: true })
  await cp(mirror, path.join(dir, 'bundle'), { recursive: true })
  await writeFile(path.join(dir, 'package.json'), JSON.stringify(manifestFor(info, slug), null, 2) + '\n', 'utf8')
  await writeFile(path.join(dir, 'extensions', 'index.js'), extensionSource({
    bundleName: info.name || slug,
    prefix: options.prefix || '',
    bridgeRoot: options.bridgeRoot || BRIDGE_ROOT,
    source: spec,
  }), 'utf8')

  let installed = false
  let note = ''
  if (options.install !== false) {
    const r = piInstall(dir)
    installed = r.ok
    note = r.out
    if (!r.ok) log('pi install refused it: ' + r.out)
  }

  const report = captured.capabilities || []
  return {
    dir,
    name: 'dsh-' + slug,
    tools: report.filter((c) => c.kind === 'tool').map((c) => (options.prefix ? options.prefix + '_' : '') + c.name),
    commands: report.filter((c) => c.kind === 'command').map((c) => c.name),
    installed,
    note,
  }
}

/** Remove a converted package. Does not uninstall it from pi. */
export async function removeConverted (slug, options = {}) {
  const dir = path.join(convertedRoot(options.env || process.env), slugOf(slug))
  await rm(dir, { recursive: true, force: true })
  return dir
}
